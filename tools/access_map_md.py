"""Turn the traced access map (tools/trace_data_access.py output) into backend/data-access-map.md.

Usage: python3 -I tools/access_map_md.py access-map.json backend/data-access-map.md
Each collection becomes one API resource. Readers and writers are the screens, chart tabs, actions
and forms that touched it while the 72 workflows and the page sweep ran.
"""
import json, sys

PHI = {'patients', 'orders', 'results', 'notes', 'mar', 'claims', 'appts', 'vitalsLog', 'carePlans', 'rrEvents', 'labOrders', 'radOrders',
       'consents', 'medrec', 'assessments', 'er', 'ot', 'daycare', 'discharges', 'tele', 'docs', 'hai', 'isolation', 'patientPatches',
       'handovers', 'crossmatch', 'insCases', 'caseDrafts', 'portalRequests', 'erx', 'sdoh', 'family', 'estimates', 'btg', 'audit'}
SECURITY = {'audit': 'Append-only schema; insert-only grant; nightly signed digest to write-once storage',
            'btg': 'Server-issued, time-boxed grant; review queue', 'users': 'Owned by the identity provider (SCIM); app keeps roles and scope only',
            'patients': 'Direct identifiers field-encrypted (envelope keys); keyed-hash search index'}

def main():
    amap = json.load(open(sys.argv[1]))
    rows = []
    for coll, d in sorted(amap.items(), key=lambda kv: -sum(kv[1]['writes'].values()) - sum(kv[1]['reads'].values())):
        if coll in ('seq', 'config') or coll.startswith('__'):
            continue
        readers = sorted([k for k in d['reads'] if k.split(':')[0] in ('screen', 'chart', 'home')], key=lambda k: -d['reads'][k])
        writers = sorted([k for k in d['writes'] if k != 'boot'], key=lambda k: -d['writes'][k])
        rows.append((coll, readers, writers))
    out = ['# Data-access map', '',
           'Generated by `tools/trace_data_access.py` (store tracing on while the 73 workflows and the full page sweep ran) and',
           '`tools/access_map_md.py`. Each collection in the client state becomes one API resource in Phase 2–4.', '',
           'Read lists can be wider than a screen strictly needs: shared helpers (notification badges, search, the patient twins list) read on behalf of whichever screen is rendering. Write lists are exact.', '',
           f'{len(rows)} collections. **PHI** marks collections holding health information (encrypted at rest, every access audited).', '',
           '| Collection | PHI | Read by (screens and chart tabs) | Written by (actions and forms) | Proposed endpoints |', '|---|---|---|---|---|']
    for coll, r, w in rows:
        ep = f'`GET /api/{coll}`' + (f', `POST /api/{coll}`, `PATCH /api/{coll}/:id`' if w else '')
        if coll == 'audit': ep = '`GET /api/audit` (auditors), writes are server-side only'
        fmt = lambda xs: ', '.join(f'`{x}`' for x in xs[:8]) + (f' +{len(xs) - 8} more' if len(xs) > 8 else '') if xs else '—'
        out.append(f'| `{coll}` | {"PHI" if coll in PHI else ""} | {fmt(r)} | {fmt(w)} | {ep} |')
    out += ['', '## Notes for the server', '']
    for k, v in SECURITY.items():
        out.append(f'- `{k}`: {v}')
    out += ['- Every PHI endpoint: authenticate (OIDC session), authorise (role + care relationship, deny by default), then write the audit row in the same transaction.',
            '- `boot` reads come from `GET /api/bootstrap`, which returns only the signed-in user\'s permitted slice.']
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
    print('wrote', sys.argv[2], len(rows), 'collections')

if __name__ == '__main__':
    main()
